-- 1. Conteos por tabla
SELECT 'CREDITO_INTEGRADO' T, COUNT(*) N FROM INAVIT_DW.CREDITO_INTEGRADO     -- 104871
UNION ALL SELECT 'DIM_ENTIDAD', COUNT(*) FROM INAVIT_DW.DIM_ENTIDAD           -- 32
UNION ALL SELECT 'DIM_PATRON', COUNT(*) FROM INAVIT_DW.DIM_PATRON             -- 15000
UNION ALL SELECT 'DIM_PERIODO', COUNT(*) FROM INAVIT_DW.DIM_PERIODO           -- 14
UNION ALL SELECT 'DIM_PRODUCTO', COUNT(*) FROM INAVIT_DW.DIM_PRODUCTO         -- 5
UNION ALL SELECT 'DIM_TRABAJADOR', COUNT(*) FROM INAVIT_DW.DIM_TRABAJADOR     -- 251272
UNION ALL SELECT 'DQ_CREDITO_HUERFANO', COUNT(*) FROM INAVIT_DW.DQ_CREDITO_HUERFANO -- 444
UNION ALL SELECT 'FACT_APORTACION', COUNT(*) FROM INAVIT_DW.FACT_APORTACION   -- 2639227
UNION ALL SELECT 'FACT_COBRANZA', COUNT(*) FROM INAVIT_DW.FACT_COBRANZA       -- 25472
UNION ALL SELECT 'FACT_PAGO', COUNT(*) FROM INAVIT_DW.FACT_PAGO               -- 2216653
UNION ALL SELECT 'FACT_SUBCUENTA', COUNT(*) FROM INAVIT_DW.FACT_SUBCUENTA     -- 251272
ORDER BY 1;

-- 2. Sumas de control de los hechos grandes
SELECT COUNT(*), SUM(MONTO_APORTACION) FROM INAVIT_DW.FACT_APORTACION;   -- 2639227 · 4,118,517,348.68
SELECT COUNT(*), SUM(MONTO_PAGO)       FROM INAVIT_DW.FACT_PAGO;         -- 2216653 · 8,960,812,221.15

